#!/usr/bin/env node
/**
 * Regenerate manifest.json and the docs that publish numbers from it.
 * Output is deterministic: no timestamps, sorted rows, one trailing newline.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { buildManifest } from "./build-manifest.js";

export const DOC_HEADER = "<!-- generated by tools/gen-docs.js; edit the source, not this file -->\n";

const root = resolve(process.argv[2] ?? process.cwd());
const manifest = buildManifest(root);

writeFileSync(join(root, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

const docs = generateDocs(manifest);
mkdirSync(join(root, "docs"), { recursive: true });
for (const [path, body] of Object.entries(docs)) {
  writeFileSync(join(root, path), body);
}
console.log(
  `wrote manifest.json and ${Object.keys(docs).length} docs (${manifest.counts.skills} skills, ${manifest.counts.playbooks} playbooks)`,
);

export function generateDocs(manifest) {
  return {
    "docs/index.md": renderIndex(manifest),
    "docs/playbooks.md": renderPlaybooks(manifest),
    "docs/capability-matrix.md": renderMatrix(manifest),
  };
}

function renderIndex(manifest) {
  const tiers = groupByTier(manifest.skills);
  const lines = [
    DOC_HEADER,
    "# vstack skill catalogue",
    "",
    `vstack ${manifest.playbookVersion} ships **${manifest.counts.skills} skills**, ` +
      `**${manifest.counts.playbooks} playbooks**, **${manifest.counts.principles} principles**, ` +
      `**${manifest.counts.roles} roles**, **${manifest.counts.rubrics} rubrics** and ` +
      `**${manifest.counts.templates} templates**.`,
    "",
    `Profiles: \`core\` ${manifest.profiles.core} skills, \`stack\` ${manifest.profiles.stack}, ` +
      `\`full\` ${manifest.profiles.full}.`,
    "",
  ];
  for (const [tier, skills] of tiers) {
    lines.push(`## ${tier} (${skills.length})`, "");
    for (const skill of skills) {
      lines.push(`- **${skill.name}** — ${skill.description || "_no description_"}`);
    }
    lines.push("");
  }
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

function renderPlaybooks(manifest) {
  const lines = [DOC_HEADER, "# Playbooks", "", `${manifest.counts.playbooks} situation-based entry points.`, ""];
  if (manifest.playbooks.length === 0) lines.push("_No playbooks yet._");
  for (const playbook of manifest.playbooks) lines.push(`- [${playbook.name}](${playbook.path})`);
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

function renderMatrix(manifest) {
  const lines = [
    DOC_HEADER,
    "# Capability matrix",
    "",
    "| Skill | Tier | Rigor | Status | OpenCode | Claude Code | Codex |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const skill of manifest.skills) {
    lines.push(
      `| \`${skill.name}\` | ${skill.tier} | ${skill.rigor} | ${skill.status} | ` +
        `${manifest.harnessSupport.opencode} | ${manifest.harnessSupport["claude-code"]} | ` +
        `${manifest.harnessSupport.codex} |`,
    );
  }
  return `${lines.join("\n")}\n`;
}

function groupByTier(skills) {
  const order = ["entry", "frame", "design", "build", "review", "continuity", "meta", "stack", "unassigned"];
  const groups = new Map(order.map((tier) => [tier, []]));
  for (const skill of skills) {
    if (!groups.has(skill.tier)) groups.set(skill.tier, []);
    groups.get(skill.tier).push(skill);
  }
  return [...groups].filter(([, list]) => list.length > 0);
}
